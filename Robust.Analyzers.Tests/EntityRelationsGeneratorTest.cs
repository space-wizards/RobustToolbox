    [Test]
    public void TestCollectionsSettings()
    {
        var result = RunGenerator("""
            [AutoGenerateEntityRelations]
            public sealed partial class FooComponent : IComponent
            {
                [AutoRelationField]
                public EntityRelation Foo;

                [AutoRelationField]
                public List<EntityRelation> ListFoo0;

                [AutoRelationField(EntityRelationCollectionOptions.NullRelation)]
                public List<EntityRelation> ListFoo1;

                [AutoRelationField]
                public HashSet<EntityRelation> SetFoo0;

                [AutoRelationField]
                public Dictionary<EntityRelation, int> DictKeyFoo0;

                [AutoRelationField]
                public Dictionary<int, EntityRelation> DictValueFoo0;

                [AutoRelationField(EntityRelationCollectionOptions.NullRelation)]
                public Dictionary<int, EntityRelation> DictValueFoo1;
            }
            """);

        ExpectNoDiagnostics(result);
        ExpectSource(
            result,
            $$"""
            // <auto-generated />

            using Robust.Shared.GameObjects;

            public partial class FooComponent
            {
            [RobustAutoGenerated]
            [global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]
            public sealed partial class FooComponent_AutoRelationsSystem : EntitySystem
            {
                public override void Initialize()
                {
                    base.Initialize();
                    SubscribeLocalEvent<FooComponent, EntityRelationDeleteEvent>(OnRelationDeleted);
                    SubscribeLocalEvent<FooComponent, EntityRelationShutdownEvent>(OnRelationsClear);
                    SubscribeLocalEvent<FooComponent, ComponentRemove>(OnRelationRemove);
                }

                private void OnRelationDeleted(Entity<FooComponent> ent, ref EntityRelationDeleteEvent args)
                {
                    if (ent.Comp.Foo == args.Relation)
                        ent.Comp.Foo = EntityRelation.Null;
                    ent.Comp.ListFoo0.Remove(args.Relation);
                    ent.Comp.ListFoo1.Remove(args.Relation);
                    ent.Comp.ListFoo1.Add(EntityRelation.Null);
                    ent.Comp.SetFoo0.Remove(args.Relation);
                    ent.Comp.DictKeyFoo0.Remove(args.Relation);
                    var toRemove1 = new List<int>();
                    foreach (var (key, value) in ent.Comp.DictValueFoo0)
                    {
                        if (value == args.Relation)
                            toRemove1.Add(key);
                    }

                    foreach (var key in toRemove1)
                    {
                        ent.Comp.DictValueFoo0.Remove(key);
                    }
                    foreach (var (key, value) in ent.Comp.DictValueFoo1)
                    {
                        if (value == args.Relation)
                            ent.Comp.DictValueFoo1[key] = EntityRelation.Null;
                    }

                }

                private void OnRelationsClear(Entity<FooComponent> ent, ref EntityRelationShutdownEvent args)
                {
                    ent.Comp.Foo = EntityRelation.Null;
                    ent.Comp.ListFoo0.Clear();
                    var count0 = ent.Comp.ListFoo1.Count;
                    ent.Comp.ListFoo1.Clear();
                    for (var i = 0; i < count0; i++)
                    {
                        ent.Comp.ListFoo1.Add(EntityRelation.Null);
                    }
                    ent.Comp.SetFoo0.Clear();
                    ent.Comp.DictKeyFoo0.Clear();
                    ent.Comp.DictValueFoo0.Clear();
                    foreach (var key in ent.Comp.DictValueFoo1.Keys)
                    {
                        ent.Comp.DictValueFoo1[key] = EntityRelation.Null;
                    }

                }

                private void OnRelationRemove(Entity<FooComponent> ent, ref ComponentRemove args)
                {
                    ClearRelation(ent.Owner, ref ent.Comp.Foo);
                    ClearRelations(ent.Owner, ent.Comp.ListFoo0);
                    ClearRelations(ent.Owner, ent.Comp.ListFoo1);
                    ClearRelations(ent.Owner, ent.Comp.SetFoo0);
                    ClearRelations(ent.Owner, ent.Comp.DictKeyFoo0);
                    ClearRelations(ent.Owner, ent.Comp.DictValueFoo0);
                    ClearRelations(ent.Owner, ent.Comp.DictValueFoo1);

                }
            }
            }

            """);
    }

    private static void ExpectSource(GeneratorRunResult result, string expected)
    {
        Assert.That(result.GeneratedSources, Has.Length.EqualTo(1));

        var source = result.GeneratedSources[0];

        Assert.That(source.SourceText.ToString(), Is.EqualTo(expected));
    }

    private static void ExpectNoDiagnostics(GeneratorRunResult result)
    {
        Assert.That(result.Diagnostics, Is.Empty);
    }

    private static GeneratorRunResult RunGenerator(string source)
    {
        Compilation compilation = CSharpCompilation.Create("compilation",
            [
                CSharpSyntaxTree.ParseText(source, path: "Source.cs"),
                CSharpSyntaxTree.ParseText(TypesCode, path: "Types.cs")
            ],
            [MetadataReference.CreateFromFile(typeof(Binder).GetTypeInfo().Assembly.Location)],
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));

        var generator = new EntityRelationsGenerator();
        GeneratorDriver driver = CSharpGeneratorDriver.Create(generator);
        driver = driver.RunGeneratorsAndUpdateCompilation(compilation, out _, out _);
        var result = driver.GetRunResult();

        return result.Results[0];
    }
