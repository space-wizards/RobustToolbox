    public void TestBasic()
    {
        var result = RunGenerator("""
            [AutoGenerateEntityRelations]
            public sealed partial class FooComponent : IComponent
            {
                [AutoRelationField]
                public EntityRelation Foo;
            }
            """);

        ExpectNoDiagnostics(result);
        ExpectSource(
            result,
            """
