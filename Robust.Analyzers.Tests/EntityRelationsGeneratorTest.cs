            [AttributeUsage(AttributeTargets.Class, Inherited = false)]
            public sealed class AutoGenerateEntityRelationsAttribute : Attribute
            {
                public readonly bool Dirty;

                public AutoGenerateEntityRelationsAttribute(bool dirty = false)
                {
                    Dirty = dirty;
                }
            }

            [AttributeUsage(AttributeTargets.Field | AttributeTargets.Property)]
            public sealed class AutoRelationFieldAttribute : Attribute
            {
                public readonly EntityRelationCollectionOptions Options;

                public AutoRelationFieldAttribute(EntityRelationCollectionOptions options = EntityRelationCollectionOptions.RemoveRelation)
                {
                    Options = options;
                }
            }

            [AttributeUsage(AttributeTargets.Field | AttributeTargets.Property)]
            public sealed class AutoNetworkedFieldAttribute : Attribute;

            public enum EntityRelationCollectionOptions : byte
            {
                RemoveRelation = 0,
                NullRelation = 1,
            }
        }

        namespace Robust.Shared.GameObjects
        {
            public interface IComponent;

            public record struct EntityRelation;

            public readonly struct EntityUid;
        }
        """;

