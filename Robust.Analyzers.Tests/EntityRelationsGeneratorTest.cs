        global using System;
        global using Robust.Shared.Analyzers;
        global using Robust.Shared.GameObjects;

        namespace Robust.Shared.Analyzers
        {
            [AttributeUsage(AttributeTargets.Class, Inherited = false)]
            public sealed class AutoGenerateEntityRelationsAttribute : Attribute
            {
                public readonly bool Dirty;

                public readonly bool ShutdownEvent;

                public AutoGenerateEntityRelationsAttribute(bool dirty = false, bool shutdownEvent = true)
                {
                    Dirty = dirty;
                    ShutdownEvent = shutdownEvent;
                }
            }

            [AttributeUsage(AttributeTargets.Field | AttributeTargets.Property)]
            public sealed class AutoRelationFieldAttribute : Attribute;
        }

        namespace Robust.Shared.GameObjects
        {
            public interface IComponent;

            public record struct EntityRelation;

            public readonly struct EntityUid;
        }
        """;

    private const string DefaultCollectionResult = """
    // <auto-generated />

    using Robust.Shared.GameObjects;

    public partial class FooComponent
    {
    [RobustAutoGenerated]
    [global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]
    public sealed partial class FooComponent_AutoRelationsSystem : EntitySystem
    {
        public override void Initialize()
        {
            base.Initialize();
            SubscribeLocalEvent<FooComponent, ComponentShutdown>(OnRelationShutdown);
            SubscribeLocalEvent<FooComponent, EntityRelationDeleteEvent>(OnRelationDeleted);
        }

        private void OnRelationDeleted(Entity<FooComponent> ent, ref EntityRelationDeleteEvent args)
        {
            ent.Comp.Foo.Remove(args.Relation);

        }

        private void OnRelationShutdown(Entity<FooComponent> ent, ref ComponentShutdown args)
        {
            FooComponent.ClearComponentRelations(ent, EntityManager);
        }
    }

        /// <summary>
        /// Auto-generated method that clears all relations in a certain entity.
        /// This has to be called on component shutdown to keep all relations correct.
        /// </summary>
        public static void ClearComponentRelations(Entity<FooComponent> ent, IEntityManager entMan)
        {
            entMan.ClearRelation(ent.Owner, ent.Comp.Foo);

        }
    }

    """;

